import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'

import { format, resolveConfig } from 'prettier'

const ROOT = resolve(import.meta.dirname, '..')
const SOURCE = resolve(ROOT, 'docs/data/coach-exercises.json')
const TARGET = resolve(ROOT, 'lib/plans/coach.ts')
const BODY_SOURCE = resolve(ROOT, 'docs/data/body-polygons.json')
const BODY_LICENSE = resolve(ROOT, 'docs/data/body-polygons.LICENSE')
const BODY_README = resolve(ROOT, 'docs/data/README.md')
const BODY_TARGET = resolve(ROOT, 'lib/design/body.ts')
const REGION_ROW = /^\|\s*([a-z ]+?)\s*\|\s*`([a-z]+)`\s*\|\s*([a-z, -]+?)\s*\|$/
const IMAGE_SOURCE = /^docs\/data\/coach-images\/([a-z0-9-]+-(?:start|end))\.jpg$/
const TARGET_REPS = { sets: 3, repsMin: 10, repsMax: 12 }
const EQUIPMENT = new Set(['dumbbell', 'barbell', 'cable', 'machine', 'body only'])

function fail(message) {
  console.error(`coach-data: ${message}`)
  process.exit(1)
}

function imagePath(source) {
  const match = IMAGE_SOURCE.exec(source)
  if (match === null) fail(`${source} is not docs/data/coach-images/<slug>-<side>.jpg`)
  return `/exercises/${match[1]}.webp`
}

function toStep(step, uuids) {
  const exerciseId = uuids[step.slug]
  if (exerciseId === undefined) fail(`${step.slug} has no entry in the uuids map`)
  if (!EQUIPMENT.has(step.equipment)) fail(`${step.slug} names unknown equipment ${step.equipment}`)
  return {
    exerciseId,
    slug: step.slug,
    name: step.name,
    how: step.how,
    images: { start: imagePath(step.images.start), end: imagePath(step.images.end) },
    muscles: { primary: step.muscles.primary, secondary: step.muscles.secondary },
    ...(step.video === undefined ? {} : { video: step.video }),
    target: TARGET_REPS,
    equipment: step.equipment,
    bodyweight: step.equipment === 'body only',
  }
}

const data = JSON.parse(readFileSync(SOURCE, 'utf8'))

const plans = data.plans.map((plan) => ({
  id: plan.id,
  title: plan.title,
  groups: plan.groups.map((group) => ({
    name: group.name,
    steps: group.steps.map((step) => toStep(step, data.uuids)),
  })),
  retired: plan.retired ?? false,
}))

const source = `// Generated by scripts/coach-data.mjs from docs/data/coach-exercises.json. Do not edit.
import type { Plan } from '../schema/plan'

export const COACH_PLANS: Plan[] = ${JSON.stringify(plans, null, 2)}
`

const options = await resolveConfig(TARGET)
writeFileSync(TARGET, await format(source, { ...options, filepath: TARGET }))

function muscleRegions(readme) {
  const rows = {}
  for (const line of readme.split('\n')) {
    const match = REGION_ROW.exec(line.trim())
    if (match === null) continue
    rows[match[1]] = {
      group: match[2],
      regions: match[3].split(',').map((region) => region.trim()),
    }
  }
  if (Object.keys(rows).length === 0) fail('docs/data/README.md has no muscle region table')
  return rows
}

const body = JSON.parse(readFileSync(BODY_SOURCE, 'utf8'))
const regions = muscleRegions(readFileSync(BODY_README, 'utf8'))
const known = new Set([...Object.keys(body.front), ...Object.keys(body.back)])
for (const [muscle, row] of Object.entries(regions)) {
  for (const region of row.regions) {
    if (!known.has(region)) fail(`${muscle} names ${region}, which body-polygons.json lacks`)
  }
}

const notice = readFileSync(BODY_LICENSE, 'utf8')
  .trimEnd()
  .split('\n')
  .map((line) => (line === '' ? ' *' : ` * ${line}`))
  .join('\n')

const bodySource = `/*
 * Generated by scripts/coach-data.mjs from docs/data/body-polygons.json and the region
 * table in docs/data/README.md. Do not edit.
 *
 * The body polygons come from ${body.source}, ${body.url}.
 *
${notice}
 */
import type { MuscleGroup } from '../schema/exercise'
import type { Muscle } from '../schema/plan'

export const BODY_VIEWBOX = '${body.viewBox}'

export const BODY_FRONT = ${JSON.stringify(body.front, null, 2)} as const satisfies Record<string, readonly string[]>

export const BODY_BACK = ${JSON.stringify(body.back, null, 2)} as const satisfies Record<string, readonly string[]>

export type FrontRegion = keyof typeof BODY_FRONT

export type BackRegion = keyof typeof BODY_BACK

export type BodyRegion = FrontRegion | BackRegion

export const MUSCLE_REGIONS: Record<Muscle, { group: MuscleGroup; regions: readonly BodyRegion[] }> = ${JSON.stringify(regions, null, 2)}
`

const bodyOptions = await resolveConfig(BODY_TARGET)
writeFileSync(BODY_TARGET, await format(bodySource, { ...bodyOptions, filepath: BODY_TARGET }))
console.log(
  `coach-data: wrote ${String(known.size)} body regions, ${String(Object.keys(regions).length)} muscles to lib/design/body.ts`,
)

const steps = plans.reduce(
  (count, plan) => count + plan.groups.reduce((sum, group) => sum + group.steps.length, 0),
  0,
)
console.log(
  `coach-data: wrote ${String(plans.length)} plans, ${String(steps)} steps to lib/plans/coach.ts`,
)
